  '      qs.push(SchemaCore.createQuestion({ id: "PR-" + i, type: "单选", stem: "实测题 " + i,',
  '        options: [{ key: "A", text: "甲" }, { key: "B", text: "乙" }, { key: "C", text: "丙" }, { key: "D", text: "丁" }],',
  '        answer: "A", points: 2 }));',
