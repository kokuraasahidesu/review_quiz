  '    await store.set(DataCore.examBodyKey(EXAM), exam);',
  '    await ExamsCore.refreshMeta(store, EXAM);',
  /* 全局设置：本轮抽 5 题、规则=完全随机、种子=1（种子固定 → 结果可复现，断言才站得住） */
  '    await ExamsCore.writeGlobalConfig(store, { pick: { mode: "random", randomBasis: "count", count: 5, seed: 1, prefer: "random" } });',
  /* 错题本：用**真的** WrongCore 写入 8 道"欠账"（没答对过） */
  '    var lb = await WrongCore.loadBook(store, EXAM);',
  '    var book = lb.book;',
  '    for (var k = 1; k <= OWED_N; k++) {',
  '      WrongCore.applyResult(book, { id: "PR-" + k, correct: false, score: 0, full: 2 },',
  '        { now: "2026-01-01T00:00:00.000Z", type: "单选", stem: "实测题 " + k });',
  '    }',
  '    var sv = await WrongCore.saveBook(store, book);',
  '    var back = await WrongCore.loadBook(store, EXAM);',
  '    return { owed: Object.keys(back.book.entries || {}).length, saved: sv.ok };',
  '  }',
  '  async function run() {',
  '    try {',
  '      note("准备：造 24 题的卷 + 8 道欠账的错题本 + 全局设置（随机 5 题 / 种子 1）");',
  '      var seeded = await seed();',
  '      step("错题本里真的写进了 8 道欠账", [seeded.owed, seeded.saved], [OWED_N, true]);',
  '',
  '      /* 切到「答题」页签（题库首页就在这个页签里） */',
  '      var tabs = Array.prototype.slice.call(document.querySelectorAll("#tabsBar [role=tab], #tabsBar .tab"));',
  '      var answerTab = tabs.filter(function (b) { return String(b.textContent).replace(/[▾▴]/g, "").trim() === "答题"; })[0];',
  '      if (answerTab) clickEl(answerTab);',
  '      if (q1("#tabsToggle") && !(q1("#tabsRow") || {}).className.match(/open/)) clickEl(q1("#tabsToggle"));',
  '',
  '      openSettings(function (start) {',
  '        if (!start) { okAll = false; note("没能进到答卷前设置页（选择器没命中？）"); return flush(); }',
  '        var row = q1("[data-exam-id=\\"" + EXAM + "\\"]");',
  '        step("从题库首页那一行点进来 → 设置页头上写着这份卷的标题（走的是真入口）",',
  '          /重新生成试卷实测卷/.test(String((q1(".pk-hd") || {}).textContent)), true);',
