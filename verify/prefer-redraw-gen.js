  '',
  '        /* 第一次：完全随机 → 5 题 → 点「再抽一次」 */',
  '        clickEl(q1("[data-pk=\\"start\\"]"));',
  '        wait(function () { return window.__attempt && idsOf().length; }, 8000, function () {',
  '          var a = idsOf();',
  '          step("开始作答：按全局设置抽 5 题", a.length, 5);',
  '          /* 用户要求：「重新生成试卷」（原「再抽一次」）挪到「返回题库」旁边（左下角固定栏）。 */',
  '          var rb = q1("#ansRedraw");',
  '          step("  答题界面里有「重新生成试卷」按钮", !!rb, true);',
  '          step("  文案就是「重新生成试卷」", String((rb || {}).textContent), "重新生成试卷");',
  '          /* 用户要求：旧的「再抽一次」字样在界面上**一处都不许剩**（手机上尤其明显）。',
